namespace SalesDashboard.Domain;

/// <summary>
/// База расчёта долей вклада внутри набора данных.
/// Числовые значения — часть публичного контракта API, менять их нельзя
/// (GrossProfit=1, Revenue=2, Units=3, AverageCheck=4).
///
/// Поле решает, как фронтенду читать и подписывать <c>ContributionDto.valueRelative</c>:
/// доля выражается либо процентом от суммы группы, либо кратностью к среднему
/// по группе. Выбор базы определяется метрикой набора.
///
/// Для суммируемых метрик (валовая прибыль, выручка, проданные штуки) доля
/// элемента — процент от суммы всех элементов набора:
///   GrossProfit: «25% от ВП»    — элемент с ВП 250 в группе с суммой ВП 1000.
///   Revenue:     «30% от выручки» — элемент с выручкой 300 в группе с суммой 1000.
///   Units:       «15% от штук»  — элемент с 15 проданными штуками в группе со 100.
///
/// Для несуммируемого среднего чека «процент от среднего» не имеет смысла,
/// поэтому доля — во сколько раз чек элемента больше среднего чека группы:
///   AverageCheck: «×2.3 к СЧ» — чек элемента 2300 при среднем чеке группы 1000.
/// </summary>
public enum ContributionBasis
{
    GrossProfit = 1,
    Revenue = 2,
    Units = 3,
    AverageCheck = 4,
}
