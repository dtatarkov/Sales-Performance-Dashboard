/**
 * Именованный датасет — набор элементов, отсортированных сервером по метрике
 * датасета (ui.md, «Тип Dataset»). Все датасеты блока приходят одновременно;
 * активный выбирает виджет локальным состоянием, без перезапроса.
 */
export type Dataset<TItem> = {
  /** Подпись метрики датасета («Валовая прибыль», «Средний чек», …). */
  name: string;
  /** Элементы, отсортированные по метрике датасета (по убыванию). */
  items: TItem[];
};