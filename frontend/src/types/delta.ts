/**
 * Единица измерения Δ: относительная (`%`) или дельта доли-процента (`п.п.`)
 * (ui.md, «Формат данных и тип Delta»).
 */
export type DeltaUnit = "percent" | "pp";

/**
 * Δ метрики к предыдущему сопоставимому периоду (ui.md, «Тип Delta»).
 * Стрелка направления берётся из знака `value`; цвет — по семантике метрики,
 * а не по направлению числа (конфиг блока виджета).
 */
export type Delta = {
  /** Величина Δ; всегда число. Неопределённая Δ выражается `Delta | null` снаружи. */
  value: number;
  /** Суффикс единицы: `percent` → `%`, `pp` → `п.п.` */
  unit: DeltaUnit;
};