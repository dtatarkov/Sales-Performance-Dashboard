/**
 * Раскрытый UTC-диапазон периода — полуинтервал [fromUtc, toUtc).
 * Результат expandDayBoundaries; тело запроса api.md строится из этих границ.
 */
export type UtcRange = {
  /** Начало периода — 00:00:00Z первого дня; граница включается. */
  fromUtc: Date;
  /** Конец периода — 00:00:00Z дня, следующего за последним; граница исключается. */
  toUtc: Date;
};